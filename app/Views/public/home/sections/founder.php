<h2 class="pfp-title">Bhrisco Jordy Dudi Padatu</h2>
<div class="pfp-divider"></div>
<p>Saat pertama kali menginjakkan kaki di Pulau Mansinam, Jordy melihat anak-anak yang semangat belajar tapi tidak punya akses. Tidak ada buku yang cukup, tidak ada guru tetap, tidak ada layanan kesehatan yang menjangkau kampung mereka.</p>
<p>Dari kepedulian itu, Papua Future Project lahir pada 2020 bukan sebagai lembaga besar dengan gedung megah, tapi sebagai gerakan kecil yang dimulai dari satu tenda belajar dan sekelompok relawan yang percaya bahwa <strong>setiap anak itu penting.</strong></p>
<p>Lima tahun kemudian, gerakan itu sudah menjangkau 700+ anak di 13 kampung, dengan 250+ relawan dari seluruh Indonesia yang bergantian hadir memberikan dampak nyata.</p>
