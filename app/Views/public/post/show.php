<p data-inline-style="news-detail-189">
              Pada pertengahan Mei 2025, ratusan buku akhirnya tiba di Pulau Mansinam setelah perjalanan panjang dari berbagai penjuru Indonesia. Anak-anak yang selama ini mengantre membaca buku yang sama kini memiliki ratusan judul baru untuk dijelajahi bersama.
            </p>
<p data-inline-style="news-detail-190">
              Donasi ini merupakan hasil gerakan pengumpulan buku yang diinisiasi oleh Papua Future Project bersama komunitas pendukung dari seluruh Indonesia. Lebih dari 3.000 orang berpartisipasi dalam kampanye ini, mengirimkan buku-buku berkualitas mulai dari buku cerita anak, sains populer, hingga buku keterampilan praktis.
            </p>
<p data-inline-style="news-detail-191">
              Pojok baca yang semula hanya memiliki segelintir buku usang kini bertransformasi menjadi ruang literasi yang hidup. Rak-rak baru berdiri di sudut tenda belajar, dipenuhi warna-warni sampul buku yang menarik perhatian anak-anak begitu mereka datang.
            </p>
<p data-inline-style="news-detail-192">
              "Ini bukan sekadar buku. Ini adalah jendela ke dunia yang selama ini belum pernah mereka lihat," kata Bhrisco Jordy Dudi Padatu, Founder Papua Future Project, saat penyerahan simbolis dilakukan di hadapan puluhan anak-anak Mansinam.
            </p>
<p>
              Kini, pojok baca di Mansinam memiliki lebih dari 700 judul buku yang siap dibaca oleh anak-anak dari 13 kampung binaan Papua Future Project. Program literasi akan terus diperluas ke kampung-kampung lain di Papua Barat dalam waktu dekat.
            </p>
