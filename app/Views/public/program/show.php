<span class="pfp-tag">Tentang Program</span>
<h2 class="pfp-title">Bimbingan Belajar &amp; Literasi</h2>
<div class="pfp-divider"></div>
<p>Di banyak kampung Papua Barat, anak-anak usia 8–12 tahun masih belum bisa membaca dan menulis. Bukan karena tidak mau belajar — tapi karena tidak ada yang mengajar mereka dengan cara yang tepat.</p>
<p>Papua Future Project hadir dengan pendekatan belajar yang disesuaikan kondisi lokal: menggunakan bahasa yang familiar, suasana yang aman, dan relawan yang sabar. Setiap sesi bimbel dirancang bersama warga, bukan sekadar mengikuti kurikulum nasional yang belum tentu relevan.</p>
<p>Hingga saat ini, <strong>700+ anak di 13 kampung</strong> sudah merasakan dampaknya. Banyak di antaranya kini bisa membaca buku pertama mereka sendiri — momen yang tidak terlupakan bagi para relawan yang mendampingi.</p>
